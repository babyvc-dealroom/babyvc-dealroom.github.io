# End-to-end: organiser sign-up, approval in the ops console, sign-in, account deletion, auto-approve.
import json, os, sys, time
from playwright.sync_api import sync_playwright
URL = os.environ.get('BVC_URL', 'http://localhost:8765/index.html'); S = os.environ.get('SHOTS', '/tmp/bvc-shots/')
PW = os.environ.get('OPS_PASSWORD', 'demo-ops-console')
checks, errs = [], []
def ok(c, m): checks.append(bool(c)); print(('ok  ' if c else 'FAIL') + ' ' + m)
with sync_playwright() as p:
    b = p.chromium.launch(**({'executable_path': os.environ['CHROME']} if os.environ.get('CHROME') else {}))
    ctx = b.new_context(locale='it-IT', viewport={'width': 1280, 'height': 900})
    def page():
        pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e))); return pg
    a = page(); a.goto(URL + '#/admin'); time.sleep(0.8)
    ok(a.get_by_role('tab', name='Crea un account').get_attribute('aria-selected') == 'true', 'a first visit opens on «Crea un account»')
    a.get_by_label('Nome e cognome').fill('Marta Rossi'); a.get_by_label('Email').fill('marta@scuola.it')
    a.locator('input[autocomplete="new-password"]').fill('corta'); a.get_by_role('button', name="Crea l'account").click(); time.sleep(0.5)
    ok(a.locator('.pending').count() == 0, 'a password under 8 characters is refused')
    a.locator('input[autocomplete="new-password"]').fill('una-password-lunga')
    a.get_by_label('Scuola, università, acceleratore o azienda (facoltativo)').fill('Liceo Volta')
    a.get_by_label('Come userai il gioco? (facoltativo)').fill('Lezione da 2 ore con 30 studenti')
    a.screenshot(path=S + 'acc-1-signup.png')
    a.get_by_role('button', name="Crea l'account").click(); time.sleep(1)
    ok(a.get_by_text('in attesa di approvazione').count() >= 1, 'after sign-up the account waits for approval')
    ok(a.get_by_role('button', name='Nuova partita').count() == 0, 'an account on hold cannot create games')
    a.screenshot(path=S + 'acc-2-pending.png')
    o = page(); o.goto(URL + '#/easteregg'); o.wait_for_selector('.ops-gate'); o.fill('input[type=password]', PW); o.get_by_role('button', name='Apri la console').click(); o.wait_for_selector('.ops-stats', timeout=8000); time.sleep(0.6)
    ok('Richieste di account in attesa' in o.locator('.issue b').all_inner_texts(), 'the console flags the waiting request')
    o.get_by_role('tab', name='Account').click(); time.sleep(0.5)
    ok(o.locator('.req.pending').count() == 1 and 'Liceo Volta' in o.locator('.req.pending').inner_text(), 'the console shows who asked, from where and why')
    o.screenshot(path=S + 'acc-3-console.png', full_page=True)
    o.locator('.req.pending').get_by_role('button', name='Approva').click(); time.sleep(0.8)
    ok(o.locator('.req.approved').count() == 1, 'one click approves the account')
    a.get_by_role('button', name='Controlla di nuovo').click(); time.sleep(1)
    ok(a.get_by_role('button', name='Nuova partita').count() == 1, 'once approved the organiser sees «Nuova partita»')
    a.get_by_role('button', name='Nuova partita').click(); a.get_by_role('button', name='Crea la partita').click(); a.wait_for_selector('.control'); time.sleep(0.5)
    ok(a.locator('.control').count() == 1, 'the approved organiser creates and runs a game')
    a.goto(URL + '#/admin'); time.sleep(0.8)
    a.get_by_role('button', name='Esci').first.click(); time.sleep(0.6)
    a.get_by_role('tab', name='Accedi').click(); a.get_by_label('Email').fill('marta@scuola.it'); a.locator('input[autocomplete="current-password"]').fill('sbagliata!!'); a.get_by_role('button', name='Accedi', exact=True).click(); time.sleep(0.5)
    ok(a.get_by_text('Email o password non corretti').count() == 1, 'a wrong password is refused')
    a.locator('input[autocomplete="current-password"]').fill('una-password-lunga'); a.get_by_role('button', name='Accedi', exact=True).click(); time.sleep(1)
    ok(a.get_by_role('heading', name='Le tue partite').count() == 1 and a.locator('.gamelist li a').count() == 1, 'signing in again shows the same games')
    a.get_by_role('button', name='Elimina il mio account').click(); time.sleep(0.3); a.get_by_role('button', name='Elimina account e partite: definitivo').click(); time.sleep(1)
    ok(a.get_by_role('tab', name='Crea un account').count() == 1, 'deleting the account signs out')
    db = json.loads(a.evaluate("localStorage.getItem('bvc-demo-v2')"))
    ok(not db['accounts'] and not db['games'], 'the account and its games are gone')
    o.get_by_role('tab', name='Account').click(); time.sleep(0.3)
    o.locator('.switch input').click(); time.sleep(0.6)
    ok(o.locator('.switch.on').count() == 1, 'auto-approve can be turned on, with a warning')
    a.get_by_label('Nome e cognome').fill('Luca'); a.get_by_label('Email').fill('luca@acc.it'); a.locator('input[autocomplete="new-password"]').fill('altra-password-1'); a.get_by_role('button', name="Crea l'account").click(); time.sleep(1)
    ok(a.get_by_role('button', name='Nuova partita').count() == 1, 'with auto-approve a new account can create games at once')
    o.locator('.switch input').click(); time.sleep(0.4)
    b.close()
print('PASSED', sum(checks), 'of', len(checks)); print('ERRORS', errs)
sys.exit(0 if all(checks) and not errs else 1)
