// Builds supabase/seed_content.sql from the confidential pack. Run: npm run seed:build
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { PRIVATE_PACK, IS_REAL_PACK } from '../scenarios/flussi-energy/resolve.mjs';

const { SECRETS } = await import(pathToFileURL(PRIVATE_PACK).href);
if (!IS_REAL_PACK) console.warn('⚠ Using the SAMPLE pack (scenarios/flussi-energy/private.sample.js). Put the real private.js next to it for a real session.');
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const rows = SECRETS.map(s => `(${s.round}, ${q(s.kind)}, ${q(s.audience)}, ${q(JSON.stringify(s.body))}::jsonb)`);
const sql = `-- Generated by scripts/build-seed.mjs from the ${IS_REAL_PACK ? 'REAL' : 'SAMPLE'} confidential pack. Do not edit by hand.
-- CONFIDENTIAL when generated from the real pack: run it in Supabase, do not commit it.
insert into scenario_secrets (round, kind, audience, body) values
${rows.join(',\n')}
on conflict (round, kind) do update set audience = excluded.audience, body = excluded.body;
`;
writeFileSync(new URL('../supabase/seed_content.sql', import.meta.url), sql);
console.log(`seed_content.sql: ${rows.length} rows (${IS_REAL_PACK ? 'real' : 'sample'} pack)`);
